"""M3, step 2: write a partner client from a mapping plan, with templates and no LLM (ADR §6).

For each response operation in the plan, the client gets `from_<operation>(payload) -> dict`, one
line per step: read the partner path, apply the step's transform, write the canonical path.
`derived` and `ask` steps are not guessed: each becomes a commented TODO, listed in `TODOS`, and its
target is left for a person to fill. The output is plain Python a reviewer can read line by line.
"""

import re
import sys
from pathlib import Path

from padan.plan import Plan, Step, load_plan
from padan.transforms import parse_transform

HEADER = '''"""Client for {spec_id}, generated by padan.generate from {source}. Do not edit.

{todos} target(s) are TODO (a derived recipe or a partner question): see TODOS.
"""

from typing import Any

from padan.runtime import (
    date_part,
    enum_map,
    first,
    get,
    minor_units_to_decimal,
    put,
    time_part,
    to_e164,
    unix_seconds_to_datetime,
)

TODOS: list[dict[str, str]] = {todo_list}
'''


def function_name(endpoint: str, direction: str) -> str:
    """'GET /bookings/{{uuid}}', 'response' -> 'from_get_bookings_uuid'."""
    words = re.findall(r"[a-z0-9]+", endpoint.lower())
    return ("from_" if direction == "response" else "to_") + "_".join(words)


def sibling(path: str, name: str) -> str:
    """A path's sibling field: ('a.b[].price', 'currency') -> 'a.b[].currency'."""
    parent = path.rsplit(".", 1)[0] if "." in path else ""
    return f"{parent}.{name}" if parent else name


def lines_for(step: Step) -> list[str]:
    """The code for one response step: a put of the transformed values, or a TODO comment."""
    source, target = step.sources[0], step.target
    if step.kind in ("derived", "ask"):
        detail = (step.detail or "").replace("\n", " ")
        return [f"    # TODO {step.kind}: {target} <- {' + '.join(step.sources)}: {detail}"]
    read = f"get(payload, {source!r})"
    if step.kind == "direct":
        return [f"    put(record, {target!r}, {read})"]
    transform = parse_transform(step.detail or "")
    args = dict(transform.args)
    if transform.name == "enum_map":
        return [f"    put(record, {target!r}, [enum_map(v, {args!r}) for v in {read}])"]
    if transform.name == "minor_units_to_decimal":
        currency = f"first(get(payload, {sibling(source, args[''])!r}))"
        return [
            f"    put(record, {target!r}, [minor_units_to_decimal(v, {currency}) for v in {read}])"
        ]
    if transform.name == "construct":
        lines = [f"    values = {read}", f"    put(record, {target!r}, values)"]
        lines += [
            f"    put(record, {sibling(target, key)!r}, [{value!r}] * len(values))"
            for key, value in transform.args
        ]
        return lines
    return [f"    put(record, {target!r}, [{transform.name}(v) for v in {read}])"]


def todos(plan: Plan) -> list[dict[str, str]]:
    return [
        {
            "operation": f"{s.endpoint} ({s.direction})",
            "target": s.target,
            "kind": s.kind,
            "sources": " + ".join(s.sources),
            "detail": s.detail or "",
        }
        for s in plan.steps
        if s.kind in ("derived", "ask")
    ]


def generate(plan: Plan, source: str) -> str:
    """The client module for `plan`: one from_… function per response operation."""
    listed = todos(plan)
    out = [HEADER.format(spec_id=plan.spec_id, source=source, todos=len(listed), todo_list=listed)]
    for endpoint, direction in plan.operations():
        if direction != "response":
            continue  # requests: to_… functions, Day 21
        out += [
            "",
            f"def {function_name(endpoint, direction)}(payload: Any) -> dict[str, Any]:",
            f'    """{endpoint} response -> a canonical booking record (validate with Booking)."""',
            "    record: dict[str, Any] = {}",
        ]
        for step in plan.for_operation(endpoint, direction):
            out += lines_for(step)
        out.append("    return record")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    """`python -m padan.generate SPEC LABEL_FILE OUT_DIR`."""
    if len(argv) != 3:
        print("usage: python -m padan.generate SPEC LABEL_FILE OUT_DIR")
        return 2
    spec_id, label_file, out_dir = argv[0], Path(argv[1]), Path(argv[2])
    plan = load_plan(spec_id, label_file)
    out = out_dir / f"client_{spec_id.replace('-', '_')}.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(plan, label_file.as_posix()))
    print(f"wrote {out}: {dict(plan.kinds())}, {len(todos(plan))} TODO(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
